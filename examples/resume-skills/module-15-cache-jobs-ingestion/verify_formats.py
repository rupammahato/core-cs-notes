from io import BytesIO
import zipfile
from defusedxml.common import DefusedXmlException
from ingestion import parse_csv,parse_xml,parse_xlsx,extract_pdf,InvalidFile,MAX_ROWS,MAX_BYTES,FIELDS,spreadsheet_safe_cell
from fixtures import csv_bytes,row,xlsx_bytes,pdf_bytes
from checks import Checks,equal,require,rejects

checks=Checks('formats');observed={}
def csv_quoted():
    records=parse_csv(b'\xef\xbb\xbf'+csv_bytes([row(name='ACME, Ltd')]))
    equal(records[0].name,'ACME, Ltd');equal(records[0].amount_minor,12500)
    observed['normalized_source_time']=records[0].source_time
    equal(records[0].source_time,'2026-10-14T06:30:00+00:00')
checks.check('UTF-8 BOM and quoted comma parse with aware UTC timestamp normalization',csv_quoted)
checks.check('CSV header mismatch is rejected',lambda:rejects(InvalidFile,lambda:parse_csv(b'wrong\nvalue\n')))
checks.check('invalid UTF-8 is rejected',lambda:rejects(InvalidFile,lambda:parse_csv(b'\xff')))
checks.check('missing CSV column is rejected',lambda:rejects(InvalidFile,lambda:parse_csv(csv_bytes([row()[:-1]]))))
checks.check('fractional minor-unit amount is rejected',lambda:rejects(InvalidFile,lambda:parse_csv(csv_bytes([row(amount='1.5')]))))
checks.check('negative minor-unit amount is rejected',lambda:rejects(InvalidFile,lambda:parse_csv(csv_bytes([row(amount='-1')]))))
checks.check('naive source timestamp is rejected',lambda:rejects(InvalidFile,lambda:parse_csv(csv_bytes([row(stamp='2026-10-14T12:00:00')]))))
checks.check('duplicate source identity within one file is rejected',lambda:rejects(InvalidFile,lambda:parse_csv(csv_bytes([row(),row()]))))
checks.check('row count beyond configured limit is rejected',lambda:rejects(InvalidFile,lambda:parse_csv(csv_bytes([row(identifier=str(i)) for i in range(MAX_ROWS+1)]))))
checks.check('raw byte budget is checked before parsing',lambda:rejects(InvalidFile,lambda:parse_csv(b'x'*(MAX_BYTES+1))))
def xml_valid():
    data=('<records><record>'+''.join('<'+k+'>'+v+'</'+k+'>' for k,v in zip(FIELDS,row()))+'</record></records>').encode()
    equal(parse_xml(data)[0],parse_csv(csv_bytes([row()]))[0])
checks.check('XML maps its explicit record fields into the same normalized model',xml_valid)
checks.check('DTD and entity-bearing XML is rejected by defusedxml',lambda:rejects(DefusedXmlException,lambda:parse_xml(b'<!DOCTYPE records [<!ENTITY x "expanded">]><records>&x;</records>')))
checks.check('unexpected XML root is rejected',lambda:rejects(InvalidFile,lambda:parse_xml(b'<other/>')))
def excel_valid():
    equal(parse_xlsx(xlsx_bytes([row(amount=12500,version=1)]))[0],parse_csv(csv_bytes([row()]))[0])
checks.check('real XLSX integer cells normalize to the CSV record model',excel_valid)
checks.check('XLSX formula cell is rejected instead of trusting cached results',lambda:rejects(InvalidFile,lambda:parse_xlsx(xlsx_bytes([row(amount='=1+2')]))))
checks.check('unexpected extra worksheet is rejected',lambda:rejects(InvalidFile,lambda:parse_xlsx(xlsx_bytes([row()],extra_sheet=True))))
def archive_budget():
    stream=BytesIO()
    with zipfile.ZipFile(stream,'w',compression=zipfile.ZIP_DEFLATED) as archive:archive.writestr('oversized.xml',b'x'*8_000_001)
    rejects(InvalidFile,lambda:parse_xlsx(stream.getvalue()))
checks.check('compressed workbook expansion budget is checked before workbook loading',archive_budget)
def macro():
    stream=BytesIO(xlsx_bytes([row()]))
    with zipfile.ZipFile(stream,'a') as archive:archive.writestr('xl/vbaProject.bin',b'fixture-not-executable')
    rejects(InvalidFile,lambda:parse_xlsx(stream.getvalue()))
checks.check('macro project content is rejected',macro)
def pdf_text():
    text=extract_pdf(pdf_bytes());equal(text,'fixture invoice');observed['pdf_text']=text
checks.check('real generated text PDF is parsed by pypdf',pdf_text)
checks.check('image-or-blank PDF with no text requires OCR or review',lambda:rejects(InvalidFile,lambda:extract_pdf(pdf_bytes(text=False))))
checks.check('encrypted PDF is rejected without attempting password recovery',lambda:rejects(InvalidFile,lambda:extract_pdf(pdf_bytes(encrypted=True))))
checks.check('PDF page budget rejects a six-page fixture',lambda:rejects(InvalidFile,lambda:extract_pdf(pdf_bytes(pages=6))))
def export_cells():
    equal(spreadsheet_safe_cell('=SUM(A1:A2)'),"'=SUM(A1:A2)")
    equal(spreadsheet_safe_cell(' ordinary'),' ordinary')
checks.check('spreadsheet export escapes formula-shaped text according to the fixture policy',export_cells)
checks.save(observations=observed,scope='Actual CSV XML XLSX and PDF libraries on generated bytes; bounded examples, not a hostile-parser sandbox or OCR engine')
